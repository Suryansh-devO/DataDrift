package com.example.datadrift.model

// ============================================================
// DataDrift - DataUsage
// ============================================================
// RESPONSIBILITY:
// Ye class ek particular data period ka usage store karegi.
//
// Example:
//
// TODAY
// Total      = 1.88 GB
// Download   = 1.42 GB
// Upload     = 460 MB
//
// CUSTOM
// Total      = 742 MB
// Download   = 580 MB
// Upload     = 162 MB
// ============================================================


// ============================================================
// DATA USAGE MODEL
// ============================================================

data class DataUsage(

    // ========================================================
    // DOWNLOAD DATA
    // ========================================================
    // Received/downloaded mobile data bytes mein.
    // ========================================================

    val downloadBytes: Long,


    // ========================================================
    // UPLOAD DATA
    // ========================================================
    // Sent/uploaded mobile data bytes mein.
    // ========================================================

    val uploadBytes: Long,


    // ========================================================
    // TOTAL DATA
    // ========================================================
    // Download + Upload.
    // ========================================================

    val totalBytes: Long,


    // ========================================================
    // PERIOD START TIME
    // ========================================================
    // Ye batayega usage kis time se calculate hua.
    //
    // Example:
    // 12:00 AM
    // ya
    // 12:00 PM
    // ========================================================

    val startTime: Long,


    // ========================================================
    // PERIOD END TIME
    // ========================================================
    // Abhi ke version mein generally current time hoga.
    // ========================================================

    val endTime: Long
)